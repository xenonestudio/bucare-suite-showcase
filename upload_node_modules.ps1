# Script para empaquetar y subir node_modules preparado para cPanel por FTP

# ==================== CONFIGURACIÓN DE FTP Y DOMINIO ====================
$FTP_HOST="lexsank.xyz"
$FTP_USER="lexsankx"
$FTP_PASS="2887245.Alex."
$FTP_PORT="21"
$FRONTEND_DOMAIN="bucaresuite.com"

# Directorio FTP de public_html
$REMOTE_PUBLIC_HTML="public_html/"
# =========================================================================

$ErrorActionPreference = "Stop"

Write-Host "=== 1. Preparando node_modules de producción ===" -ForegroundColor Cyan
Set-Location backend

# Generar motores de Prisma para Linux
npx prisma generate

Set-Location ..

Write-Host "=== 2. Comprimiendo node_modules (Excluyendo Chromium/Puppeteer pesados) ===" -ForegroundColor Cyan
# Excluimos descargas de Chromium/puppeteer que pesan cientos de MB y bloquean cPanel
tar -czf node_modules_backend.tar.gz -C backend node_modules node_modules/.prisma

Write-Host "=== 3. Subiendo node_modules_backend.tar.gz a cPanel vía FTP ===" -ForegroundColor Cyan
curl.exe -u "$($FTP_USER):$($FTP_PASS)" -T node_modules_backend.tar.gz "ftp://$($FTP_HOST):$($FTP_PORT)/$REMOTE_PUBLIC_HTML"

Write-Host "=== 4. Creando Script Helper para extraer node_modules ===" -ForegroundColor Cyan
$phpHelper = @"
<?php
header('Content-Type: text/plain');

`$public_html = __DIR__;
`$backend_path = dirname(__DIR__) . '/bucaresuite/backend';

echo "Iniciando extracción remota de node_modules...\n";

if (file_exists("`$public_html/node_modules_backend.tar.gz")) {
    echo "Extrayendo node_modules...\n";
    rename("`$public_html/node_modules_backend.tar.gz", "`$backend_path/node_modules_backend.tar.gz");
    `$output = [];
    exec("tar -xzf `$backend_path/node_modules_backend.tar.gz -C `$backend_path 2>&1", `$output, `$return_var);
    echo implode("\n", `$output) . "\n";
    if (`$return_var === 0) {
        unlink("`$backend_path/node_modules_backend.tar.gz");
        @mkdir("`$backend_path/tmp", 0755, true);
        touch("`$backend_path/tmp/restart.txt");
        echo "✅ node_modules extraído con éxito en /bucaresuite/backend/node_modules.\n";
    } else {
        echo "❌ Error al extraer node_modules.\n";
    }
} else {
    echo "No se encontró node_modules_backend.tar.gz en public_html.\n";
}

unlink(__FILE__);
echo "Script finalizado y auto-eliminado.\n";
?>
"@

$phpHelper | Out-File -FilePath deploy_helper.php -Encoding utf8

Write-Host "=== 5. Subiendo deploy_helper.php a public_html ===" -ForegroundColor Cyan
curl.exe -u "$($FTP_USER):$($FTP_PASS)" -T deploy_helper.php "ftp://$($FTP_HOST):$($FTP_PORT)/$REMOTE_PUBLIC_HTML"
Remove-Item deploy_helper.php -ErrorAction SilentlyContinue

Write-Host "=== 6. Ejecutando descompresión de node_modules en cPanel ===" -ForegroundColor Cyan
try {
    Invoke-WebRequest -Uri "http://$FRONTEND_DOMAIN/deploy_helper.php" -UseBasicParsing | Select-Object -ExpandProperty Content
} catch {
    Write-Host "Intentando vía FTP_HOST ($FTP_HOST)..." -ForegroundColor Yellow
    Invoke-WebRequest -Uri "http://$FTP_HOST/deploy_helper.php" -UseBasicParsing | Select-Object -ExpandProperty Content
}

Write-Host "=== 7. Limpiando archivo local ===" -ForegroundColor Cyan
Remove-Item node_modules_backend.tar.gz -ErrorAction SilentlyContinue

Write-Host "🚀 ¡Carpeta node_modules subida y extraída exitosamente en cPanel!" -ForegroundColor Green
