<?php
header('Content-Type: text/plain');
$nodeModules = '/home/lexsankx/bucaresuite/backend/node_modules';

echo "Checking: $nodeModules\n";
if (is_link($nodeModules)) {
    echo "Already a symlink -> " . readlink($nodeModules) . "\n";
    echo "No action needed.\n";
} elseif (is_dir($nodeModules)) {
    echo "Found real directory. Removing...\n";
    $out = []; $code = -1;
    exec("rm -rf " . escapeshellarg($nodeModules) . " 2>&1", $out, $code);
    echo "Exit code: $code\n";
    echo implode("\n", $out) . "\n";
    echo is_dir($nodeModules) ? "STILL EXISTS - failed!\n" : "Removed successfully!\n";
} else {
    echo "node_modules does not exist. cPanel can now create the symlink.\n";
}
unlink(__FILE__);
?>
